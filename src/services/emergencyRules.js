/**
 * Checks if a symptom name or description matches conservative emergency criteria.
 * @param {string} symptomName 
 * @param {string} description 
 * @param {string} severity 
 * @returns {object|null} Matched emergency rule or null
 */
export function evaluateSymptomSafety(symptomName = '', description = '', severity = '') {
  const textToScan = `${symptomName.toLowerCase()} ${description.toLowerCase()}`;

  for (const trigger of EMERGENCY_SYMPTOM_TRIGGERS) {
    for (const kw of trigger.keywords) {
      if (textToScan.includes(kw.toLowerCase())) {
        return {
          isEmergency: true,
          trigger,
          matchedKeyword: kw,
          reason: `Conservative safety rule triggered for "${kw}".`,
          disclaimer: 'This warning is generated by an automated safety rule and is not a medical diagnosis. A doctor or emergency service must evaluate these symptoms.'
        };
      }
    }
  }

  // If marked Severe and includes words like "unbearable", "worst ever", "extreme"
  if (severity === 'Severe') {
    const highIntensityWords = ['unbearable', 'worst', 'extreme', 'cannot stand', 'bleeding heavily', 'high fever'];
    for (const word of highIntensityWords) {
      if (textToScan.includes(word)) {
        return {
          isEmergency: true,
          trigger: {
            category: 'Severe High-Intensity Symptom',
            title: 'High Severity Warning',
            urgency: 'URGENT MEDICAL ATTENTION',
            advice: 'You have logged a severe symptom marked as unbearable or extreme. Please contact your doctor or visit urgent care promptly.',
            emergencyNumber: '112 / 108'
          },
          matchedKeyword: word,
          reason: `High intensity flag "${word}" in severe symptom report.`,
          disclaimer: 'ElderCare 360 conservative safety notice.'
        };
      }
    }
  }

  return null;
}

/**
 * Checks if conversational text contains crisis or self-harm expressions.
 * @param {string} messageText 
 * @returns {object|null}
 */
export function evaluateCrisisSafety(messageText = '') {
  if (!messageText) return null;
  const normalized = messageText.toLowerCase();

  for (const expr of CRISIS_EXPRESSIONS) {
    if (normalized.includes(expr)) {
      return {
        isCrisis: true,
        matchedExpression: expr,
        helplines: [
          { name: 'India National Emergency', number: '112', type: 'Emergency Response' },
          { name: 'Tele-MANAS (Govt of India Mental Health)', number: '14416', type: '24/7 Free Confidential Support' },
          { name: 'Vandrevala Foundation Helpline', number: '+91 9999 666 555', type: '24/7 Mental Health Support' },
          { name: 'KIRAN National Mental Health Helpline', number: '1800-599-0019', type: 'Toll-free 24/7' }
        ],
        message: 'I hear how much pain you are carrying right now, and I care deeply about your well-being. You are not alone, and help is available right now. Are you in a safe place?'
      };
    }
  }

  return null;
}
